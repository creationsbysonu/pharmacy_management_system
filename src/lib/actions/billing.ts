"use server";

import { revalidatePath } from "next/cache";
import type { FormState } from "@/lib/actions/auth";
import { requireAccess } from "@/lib/auth";
import { buildInvoicePdf, invoiceFilename, loadInvoice } from "@/lib/invoice";
import {
  invoiceBrand,
  invoiceSender,
  loadPharmacyProfile,
} from "@/lib/pharmacy";
import { createClient } from "@/lib/supabase/server";

const RESEND_ENDPOINT = "https://api.resend.com/emails";

/**
 * Emails a customer their invoice as a PDF.
 *
 * The customer must already have an email on file — this never takes an address
 * from the form, so a pharmacist cannot use the till to send mail to an address
 * the pharmacy never registered. Every attempt is written to invoice_email so
 * the delivery state is visible on the sale.
 */
export async function emailInvoice(
  _previous: FormState,
  formData: FormData,
): Promise<FormState> {
  const access = await requireAccess();
  const saleId = Number(formData.get("sale_id"));

  if (!Number.isInteger(saleId)) return { error: "That sale could not be found." };
  if (access.readOnly) {
    return { error: "The trial has ended, so invoices cannot be emailed until a plan is active." };
  }

  const pharmacy = await loadPharmacyProfile(access.workspaceId);
  const invoice = await loadInvoice(saleId, invoiceBrand(pharmacy, access.pharmacyName));
  if (!invoice) return { error: "That sale could not be found in this pharmacy." };

  if (!invoice.customer) {
    return { error: "This was a walk-in sale. Add the customer to the sale to email an invoice." };
  }
  if (!invoice.customer.email) {
    return {
      error:
        "This customer has no email address on file. Add one to their record, then try again.",
    };
  }

  const apiKey = process.env.RESEND_API_KEY;
  if (!apiKey) {
    return {
      error:
        "Email delivery is not switched on for this deployment. Add RESEND_API_KEY to the environment, then redeploy.",
    };
  }

  const sender = invoiceSender(pharmacy, access.pharmacyName);
  if (sender.source === "sandbox") {
    return {
      error:
        "This pharmacy has no sender address yet. Add its invoice email in Settings → Pharmacy, or set INVOICE_FROM_EMAIL for the deployment. Mail from the Resend sandbox address only reaches the account owner.",
    };
  }

  const pdf = buildInvoicePdf(invoice);
  const base64 = Buffer.from(pdf).toString("base64");
  const filename = invoiceFilename(invoice);

  let status: "sent" | "failed" = "sent";
  let providerId: string | null = null;
  let failure: string | null = null;

  try {
    const response = await fetch(RESEND_ENDPOINT, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        from: sender.from,
        ...(sender.replyTo ? { reply_to: sender.replyTo } : {}),
        to: [invoice.customer.email],
        subject: `Your invoice INV-${String(invoice.saleId).padStart(5, "0")} from ${invoice.pharmacy.name}`,
        html: `
          <div style="font-family:ui-sans-serif,system-ui,sans-serif;color:#16202a;line-height:1.6">
            <p>Hello ${invoice.customer.name.split(" ")[0] || "there"},</p>
            <p>Thank you for shopping at <strong>${invoice.pharmacy.name}</strong>.
            Your invoice for <strong>Rs. ${invoice.total.toFixed(2)}</strong> is attached as a PDF.</p>
            <p style="color:#5b6b73;font-size:13px">Invoice INV-${String(invoice.saleId).padStart(5, "0")} ·
            ${new Date(invoice.soldAt).toLocaleDateString("en-IN")}</p>
            <p style="color:#5b6b73;font-size:12px">Generated by Pharmacia. Keep this receipt for returns and insurance claims.</p>
          </div>
        `,
        attachments: [{ filename, content: base64 }],
      }),
    });

    if (!response.ok) {
      status = "failed";
      const text = await response.text();
      failure = text.slice(0, 300);
    } else {
      const payload = (await response.json().catch(() => null)) as { id?: string } | null;
      providerId = payload?.id ?? null;
    }
  } catch (error) {
    status = "failed";
    failure = error instanceof Error ? error.message.slice(0, 300) : "Network error";
  }

  const supabase = await createClient();
  await supabase.from("invoice_email").insert({
    workspace_id: access.workspaceId,
    sale_id: invoice.saleId,
    to_email: invoice.customer.email,
    status,
    provider: "resend",
    provider_id: providerId,
    error: failure,
    sent_by: access.user.id,
  });

  revalidatePath(`/sales/${invoice.saleId}`);

  if (status === "failed") {
    return {
      error: `The email provider rejected the message${failure ? `: ${failure}` : "."} The PDF can still be downloaded and printed.`,
    };
  }

  return { message: `Invoice sent to ${invoice.customer.email}.` };
}
