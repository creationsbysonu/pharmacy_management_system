-- =============================================================================
-- Account settings, staff access and audit trail
--
--   * profile and pharmacy details can be edited through narrow RPCs, because
--     authenticated clients have no write access to profiles/workspaces
--   * an administrator can attach an existing account to their workspace as a
--     pharmacist, or detach them again
--   * every insert, update and delete on the business tables is recorded in
--     public.audit_log
--
-- Apply after 0003_security_hardening.sql. Safe to run more than once.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Audit log
-- ---------------------------------------------------------------------------
create table if not exists public.audit_log (
  id           bigint generated by default as identity primary key,
  workspace_id uuid not null,
  actor        uuid,
  actor_email  text,
  action       text not null check (action in ('insert', 'update', 'delete')),
  entity       text not null,
  entity_id    text,
  summary      text not null default '',
  created_at   timestamptz not null default now()
);

create index if not exists audit_log_workspace_idx
  on public.audit_log (workspace_id, created_at desc);

alter table public.audit_log enable row level security;

drop policy if exists audit_log_admin_read on public.audit_log;
create policy audit_log_admin_read on public.audit_log
  for select to authenticated
  using (is_member(workspace_id) and is_admin());

revoke insert, update, delete on public.audit_log from authenticated, anon;
grant select on public.audit_log to authenticated;

-- One generic trigger per table; the primary key column is passed as an
-- argument so the row can be labelled without a per-table function.
create or replace function public.audit_row()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_row      jsonb;
  v_old      jsonb;
  v_changed  text[] := '{}';
  v_key      text;
  v_summary  text;
  v_pk_col   text := coalesce(nullif(tg_argv[0], ''), 'id');
begin
  if tg_op = 'DELETE' then
    v_row := to_jsonb(old);
    v_old := null;
  elsif tg_op = 'UPDATE' then
    v_row := to_jsonb(new);
    v_old := to_jsonb(old);
    for v_key in select jsonb_object_keys(v_row) loop
      if v_row -> v_key is distinct from v_old -> v_key then
        v_changed := v_changed || v_key;
      end if;
    end loop;
    if array_length(v_changed, 1) is null then
      return new;  -- nothing actually changed
    end if;
  else
    v_row := to_jsonb(new);
    v_old := null;
  end if;

  if tg_op = 'update' then
    select string_agg(format('%s → %s', t.key, coalesce(v_row ->> t.key, '—')), ', ')
      into v_summary
      from unnest(v_changed) as t(key);
  elsif tg_op = 'insert' then
    select string_agg(format('%s=%s', t.key, coalesce(v_row ->> t.key, '—')), ', ')
      into v_summary
      from jsonb_object_keys(v_row) as t(key)
     where t.key not in ('workspace_id', 'created_at');
  else
    v_summary := format('%s removed', coalesce(v_row ->> 'med_name', v_row ->> 'sup_name', v_row ->> 'c_fname', v_row ->> 'e_fname', v_row ->> v_pk_col, tg_table_name));
  end if;

  insert into public.audit_log (workspace_id, actor, actor_email, action, entity, entity_id, summary)
  values (
    (v_row ->> 'workspace_id')::uuid,
    auth.uid(),
    nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'email',
    lower(tg_op),
    tg_table_name,
    v_row ->> v_pk_col,
    left(coalesce(v_summary, ''), 500)
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end $$;

do $$
declare
  spec record;
begin
  for spec in
    select * from (values
      ('meds', 'med_id'),
      ('suppliers', 'sup_id'),
      ('customer', 'c_id'),
      ('employee', 'e_id'),
      ('purchase', 'p_id'),
      ('sales', 'sale_id')
    ) as t(tbl, pk)
  loop
    execute format('drop trigger if exists %I on public.%I', 'audit_' || spec.tbl, spec.tbl);
    execute format(
      'create trigger %I after insert or update or delete on public.%I
         for each row execute function public.audit_row(%L)',
      'audit_' || spec.tbl, spec.tbl, spec.pk
    );
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Profile and pharmacy details
-- ---------------------------------------------------------------------------
create or replace function public.update_my_profile(p_full_name text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required.' using errcode = '28000';
  end if;
  if length(coalesce(trim(p_full_name), '')) < 2 then
    raise exception 'Enter a name of at least two characters.' using errcode = '22023';
  end if;

  update public.profiles
     set full_name = left(trim(p_full_name), 80)
   where id = auth.uid();
end $$;

create or replace function public.update_my_workspace(p_name text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_workspace uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required.' using errcode = '28000';
  end if;
  if not public.is_admin() then
    raise exception 'Only an administrator can rename the pharmacy.' using errcode = '42501';
  end if;
  if length(coalesce(trim(p_name), '')) < 2 then
    raise exception 'Enter a pharmacy name of at least two characters.' using errcode = '22023';
  end if;

  select m.workspace_id into v_workspace
    from public.workspace_members m
    join public.workspaces w on w.id = m.workspace_id
   where m.user_id = auth.uid() and w.status = 'active'
   order by m.created_at asc
   limit 1;

  if v_workspace is null then
    raise exception 'No active pharmacy workspace.' using errcode = '42501';
  end if;

  update public.workspaces set name = left(trim(p_name), 80) where id = v_workspace;
end $$;

-- ---------------------------------------------------------------------------
-- Staff membership: an administrator can attach an existing account to their
-- workspace as a pharmacist, and remove it again. Creating the account itself
-- needs the Supabase admin API (see lib/actions/staff.ts).
-- ---------------------------------------------------------------------------
-- Replaced by the three-argument version below, which can also attach the
-- new login to an existing row in public.employee.
drop function if exists public.adopt_staff(uuid, text);

create or replace function public.adopt_staff(
  p_user_id uuid,
  p_full_name text default null,
  p_employee_id integer default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_workspace uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required.' using errcode = '28000';
  end if;
  if not public.is_admin() then
    raise exception 'Only an administrator can add staff.' using errcode = '42501';
  end if;
  if p_user_id = auth.uid() then
    raise exception 'You are already in this workspace.' using errcode = '22023';
  end if;

  select m.workspace_id into v_workspace
    from public.workspace_members m
    join public.workspaces w on w.id = m.workspace_id
   where m.user_id = auth.uid() and w.status = 'active'
   order by m.created_at asc
   limit 1;

  if v_workspace is null then
    raise exception 'No active pharmacy workspace.' using errcode = '42501';
  end if;

  if p_employee_id is not null and not exists (
    select 1 from public.employee e
     where e.e_id = p_employee_id and e.workspace_id = v_workspace
  ) then
    raise exception 'That employee is not in this pharmacy.' using errcode = '22023';
  end if;

  -- Never take over an account that is already running its own pharmacy: that
  -- would hand the wrong administrator access to somebody else's workspace and
  -- detach their own data mid-flight.
  if exists (
    select 1 from public.workspaces w
     where w.created_by = p_user_id
       and (
         exists (select 1 from public.meds m where m.workspace_id = w.id)
         or exists (select 1 from public.sales s where s.workspace_id = w.id)
         or exists (select 1 from public.purchase p where p.workspace_id = w.id)
         or exists (select 1 from public.customer c where c.workspace_id = w.id)
       )
  ) then
    raise exception 'That email already runs its own pharmacy. Use a different address, or have that owner remove it first.' using errcode = '22023';
  end if;

  insert into public.profiles (id, full_name, role, employee_id)
  values (
    p_user_id,
    nullif(trim(coalesce(p_full_name, '')), ''),
    'pharmacist',
    p_employee_id
  )
  on conflict (id) do update
    set role = 'pharmacist',
        full_name = coalesce(nullif(trim(coalesce(p_full_name, '')), ''), public.profiles.full_name),
        employee_id = coalesce(p_employee_id, public.profiles.employee_id);

  -- The signup trigger gives every new account its own empty trial workspace.
  -- Detach it so the person belongs to the inviting pharmacy only.
  delete from public.workspace_members m
        using public.workspaces w
        where m.workspace_id = w.id
          and w.created_by = p_user_id
          and m.user_id = p_user_id;

  delete from public.workspaces w
        where w.created_by = p_user_id
          and not exists (
            select 1 from public.workspace_members m where m.workspace_id = w.id
          );

  insert into public.workspace_members (workspace_id, user_id)
  values (v_workspace, p_user_id)
  on conflict do nothing;
end $$;

create or replace function public.remove_staff(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_workspace uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required.' using errcode = '28000';
  end if;
  if not public.is_admin() then
    raise exception 'Only an administrator can remove staff.' using errcode = '42501';
  end if;
  if p_user_id = auth.uid() then
    raise exception 'You cannot remove your own access.' using errcode = '22023';
  end if;

  select m.workspace_id into v_workspace
    from public.workspace_members m
   where m.user_id = auth.uid()
   order by m.created_at asc
   limit 1;

  if v_workspace is null then
    raise exception 'No active pharmacy workspace.' using errcode = '42501';
  end if;

  delete from public.workspace_members
   where workspace_id = v_workspace and user_id = p_user_id;

  update public.profiles set employee_id = null where id = p_user_id;
end $$;

-- ---------------------------------------------------------------------------
-- Grants: only the narrow RPCs above are callable, nothing else changed.
-- ---------------------------------------------------------------------------
revoke execute on function public.update_my_profile(text) from public, anon;
revoke execute on function public.update_my_workspace(text) from public, anon;
revoke execute on function public.adopt_staff(uuid, text, integer) from public, anon;
revoke execute on function public.remove_staff(uuid) from public, anon;
revoke execute on function public.audit_row() from public, anon, authenticated;

grant execute on function public.update_my_profile(text) to authenticated;
grant execute on function public.update_my_workspace(text) to authenticated;
grant execute on function public.adopt_staff(uuid, text, integer) to authenticated;
grant execute on function public.remove_staff(uuid) to authenticated;

-- A view models the roster the settings page reads: everyone in my workspace.
-- It deliberately runs with the owner's rights so it can join profiles (which
-- are otherwise readable only by their own account) and lists just the
-- workspaces the caller is a member of.
create or replace view public.v_workspace_members as
  select m.workspace_id,
         m.user_id,
         m.created_at as joined_at,
         p.full_name,
         p.role,
         p.employee_id,
         e.e_fname,
         e.e_lname
    from public.workspace_members m
    left join public.profiles p on p.id = m.user_id
    left join public.employee e on e.e_id = p.employee_id
   where public.is_member(m.workspace_id);

grant select on public.v_workspace_members to authenticated;
