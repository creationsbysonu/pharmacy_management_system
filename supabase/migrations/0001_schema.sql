-- ---------------------------------------------------------------------------
-- Stock synchronisation triggers (replaces QTYINSERT / QTYDELETE / QTYUPDATE
-- and SALEINSERT / SALEDELETE from the MySQL schema)
-- ---------------------------------------------------------------------------

-- Purchases add stock; edits and deletions take it back.
create or replace function public.purchase_stock_sync()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.meds set med_qty = med_qty + new.p_qty where med_id = new.med_id;
    return new;
  elsif tg_op = 'DELETE' then
    update public.meds set med_qty = greatest(0, med_qty - old.p_qty) where med_id = old.med_id;
    return old;
  elsif tg_op = 'UPDATE' then
    if old.med_id = new.med_id then
      update public.meds
         set med_qty = greatest(0, med_qty - old.p_qty) + new.p_qty
       where med_id = new.med_id;
    else
      update public.meds set med_qty = greatest(0, med_qty - old.p_qty) where med_id = old.med_id;
      update public.meds set med_qty = med_qty + new.p_qty where med_id = new.med_id;
    end if;
    return new;
  end if;
  return null;
end $$;

drop trigger if exists purchase_stock_sync on public.purchase;
create trigger purchase_stock_sync
  after insert or update or delete on public.purchase
  for each row execute function public.purchase_stock_sync();

-- Sale items take stock; deleting a line gives it back. The meds.med_qty >= 0
-- check constraint makes overselling fail loudly instead of going negative.
create or replace function public.sales_item_stock_sync()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.meds set med_qty = med_qty - new.sale_qty where med_id = new.med_id;
    return new;
  elsif tg_op = 'DELETE' then
    update public.meds set med_qty = med_qty + old.sale_qty where med_id = old.med_id;
    return old;
  end if;
  return null;
end $$;

drop trigger if exists sales_item_stock_sync on public.sales_items;
create trigger sales_item_stock_sync
  after insert or delete on public.sales_items
  for each row execute function public.sales_item_stock_sync();

-- ---------------------------------------------------------------------------
-- Profiles: one row per auth user, carrying the app role
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- The role is deliberately NOT read from raw_user_meta_data: signup metadata is
  -- attacker controlled, so a self-service signup must never be able to grant
  -- itself admin. New accounts always start as pharmacists and are promoted with
  -- an explicit update by a database owner (see demo-users.sql / the README).
  insert into public.profiles (id, full_name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, ''), '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- Role helpers used by the policies below
-- ---------------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select role = 'admin' from public.profiles where id = auth.uid()), false)
$$;

