create table if not exists public.suppliers (
  sup_id     integer generated by default as identity primary key,
  sup_name   text not null,
  sup_add    text not null default '',
  sup_phno   text not null default '',
  sup_mail   text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.meds (
  med_id        integer generated by default as identity primary key,
  med_name      text not null,
  med_qty       integer not null default 0 check (med_qty >= 0),
  category      text,
  med_price     numeric(10, 2) not null default 0 check (med_price >= 0),
  location_rack text,
  created_at    timestamptz not null default now()
);

create table if not exists public.customer (
  c_id       integer generated by default as identity primary key,
  c_fname    text not null,
  c_lname    text,
  c_age      integer check (c_age is null or c_age >= 0),
  c_sex      text,
  c_phno     text,
  c_mail     text,
  created_at timestamptz not null default now()
);

create table if not exists public.employee (
  e_id       integer generated by default as identity primary key,
  e_fname    text not null,
  e_lname    text,
  bdate      date,
  e_age      integer check (e_age is null or e_age >= 0),
  e_sex      text,
  e_type     text not null default 'Pharmacist',
  e_jdate    date,
  e_sal      numeric(10, 2) not null default 0 check (e_sal >= 0),
  e_phno     text,
  e_mail     text,
  e_add      text,
  created_at timestamptz not null default now()
);

create table if not exists public.purchase (
  p_id       integer generated by default as identity primary key,
  sup_id     integer references public.suppliers (sup_id) on delete set null,
  med_id     integer not null references public.meds (med_id) on delete cascade,
  p_qty      integer not null check (p_qty > 0),
  p_cost     numeric(10, 2) not null default 0 check (p_cost >= 0),
  pur_date   date not null default current_date,
  mfg_date   date,
  exp_date   date,
  created_at timestamptz not null default now()
);

create table if not exists public.sales (
  sale_id   integer generated by default as identity primary key,
  c_id      integer references public.customer (c_id) on delete set null,
  e_id      integer references public.employee (e_id) on delete set null,
  sold_at   timestamptz not null default now(),
  total_amt numeric(10, 2) not null default 0
);

create table if not exists public.sales_items (
  sale_id   integer not null references public.sales (sale_id) on delete cascade,
  med_id    integer not null references public.meds (med_id) on delete restrict,
  sale_qty  integer not null check (sale_qty > 0),
  tot_price numeric(10, 2) not null default 0,
  primary key (sale_id, med_id)
);

create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  full_name   text,
  role        public.user_role not null default 'pharmacist',
  employee_id integer references public.employee (e_id) on delete set null,
  created_at  timestamptz not null default now()
);

