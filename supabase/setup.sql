create or replace view public.v_expiring
with (security_invoker = true) as
  select p.p_id,
         p.exp_date,
         p.p_qty,
         p.med_id,
         m.med_name,
         s.sup_name,
         (p.exp_date - current_date) as days_left
    from public.purchase p
    join public.meds m on m.med_id = p.med_id
    left join public.suppliers s on s.sup_id = p.sup_id
   where p.exp_date is not null
     and p.exp_date <= current_date + interval '6 months'
   order by p.exp_date asc;

